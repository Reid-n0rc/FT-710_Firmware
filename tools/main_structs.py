#!/usr/bin/env python3
"""T24 (MAIN): the typed state blocks of tools/ghidra/structs_main.h as a C header for the recreated source.

tools/ghidra/structs_main.h is the source of truth for MAIN's structures (T23c; ApplyStructs.java puts them into
Ghidra). Its format places every field at an explicit offset and leaves the bytes between fields undefined, so it is
not a C header itself. This script turns it into one: each structure becomes a packed C struct with filler arrays
over the undefined bytes (RX has unaligned loads and stores, so `packed` costs nothing; GCC for RX keeps the plain
access widths [fact: a test compile, T24 MAIN round 3]), a `_Static_assert` per field offset and per size, enum
fields as integers of the enum's `@size` (tools/ghidra/enums_main.h, included for the values), and an `extern`
declaration per typed global. The globals' addresses (`@0x...`) are read by tools/equiv_main_emu.py, which defines
them when it links a recreated function, the same way as src/main/data_symbols.tsv.

Usage:
  python3 -I tools/main_structs.py OUT.h          write the header (src/main/Makefile does, at build time)
  python3 -I tools/main_structs.py --globals      print name, address of each typed global
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
STRUCTS = os.path.join(ROOT, 'tools/ghidra/structs_main.h')
ENUMS = os.path.join(ROOT, 'tools/ghidra/enums_main.h')

BASE = {'uint8_t': 1, 'int8_t': 1, 'char': 1, 'uint16_t': 2, 'int16_t': 2, 'uint32_t': 4, 'int32_t': 4}
OPEN = re.compile(r'^struct (\w+) \{\s*/\*\s*size 0x([0-9A-Fa-f]+)')
FIELD = re.compile(r'^\s+((?:struct |enum )?\w+)\s*(\*?)\s*(\w+)((?:\[\d+\])*)\s*;\s*/\*\s*\+0x([0-9A-Fa-f]+)')
GLOBAL = re.compile(r'^((?:struct |enum )?\w+)\s*(\*?)\s*(\w+)((?:\[\d+\])*)\s*;\s*/\*\s*@0x([0-9A-Fa-f]+)')


def enum_sizes():
    sizes, pending = {}, None
    with open(ENUMS, encoding='utf-8') as f:
        for line in f:
            m = re.search(r'@size (\d+)', line)
            if m:
                pending = int(m.group(1))
            m = re.match(r'^enum (\w+)', line)
            if m and pending:
                sizes[m.group(1)], pending = pending, None
    return sizes


def parse():
    """([(name, size, [(type, ptr, name, dims, offset)])], [(type, ptr, name, dims, address)])"""
    structs, globs, cur = [], [], None
    with open(STRUCTS, encoding='utf-8') as f:
        for line in f:
            m = OPEN.match(line)
            if m:
                cur = (m.group(1), int(m.group(2), 16), [])
                continue
            if cur is not None:
                if line.startswith('};'):
                    structs.append(cur)
                    cur = None
                    continue
                m = FIELD.match(line)
                if m:
                    t, p, n, d, o = m.groups()
                    cur[2].append((t, p, n, [int(x) for x in re.findall(r'\d+', d)], int(o, 16)))
                continue
            m = GLOBAL.match(line)
            if m and '(' not in line.split(';')[0]:
                t, p, n, d, a = m.groups()
                globs.append((t, p, n, [int(x) for x in re.findall(r'\d+', d)], int(a, 16)))
    return structs, globs


def ctype(t, ptr, esz):
    """C spelling and element size of a field type."""
    if ptr:
        return (t if not t.startswith('enum ') else 'uint8_t') + ' *', 4
    if t.startswith('enum '):
        n = esz[t[5:]]
        return {1: 'uint8_t', 2: 'uint16_t', 4: 'uint32_t'}[n], n
    if t.startswith('struct '):
        return t, None
    return t, BASE[t]


def header():
    esz = enum_sizes()
    structs, globs = parse()
    ssz = {n: s for n, s, _ in structs}
    out = ['/* Generated by tools/main_structs.py from tools/ghidra/structs_main.h (T23c, the source of truth); do not',
           ' * edit. The packed structs keep the image\'s layout: filler arrays (_u<offset>) cover the bytes no field',
           ' * names yet, and every offset is asserted. Enum fields hold the values of enums_main.h. */',
           '#ifndef FT710_STATE_H', '#define FT710_STATE_H', '', '#include <stddef.h>', '#include <stdint.h>',
           '#include "enums_main.h"           /* tools/ghidra/, on the include path (src/main/Makefile) */', '']
    for name, size, fields in structs:
        out.append(f'struct __attribute__((packed)) {name} {{')
        pos, asserts = 0, []
        for t, p, n, dims, off in sorted(fields, key=lambda x: x[4]):
            ct, el = ctype(t, p, esz)
            if el is None:
                el = ssz[t[7:]]
            cnt = 1
            for d in dims:
                cnt *= d
            if off < pos:
                sys.exit(f'main_structs: {name}.{n} at +0x{off:X} overlaps the field before it')
            if off > pos:
                out.append(f'    uint8_t _u{pos:03x}[0x{off - pos:X}];')
            out.append(f'    {ct}{"" if ct.endswith("*") else " "}{n}{"".join(f"[{d}]" for d in dims)};')
            asserts.append(f'_Static_assert(offsetof(struct {name}, {n}) == 0x{off:X}, "{name}.{n}");')
            pos = off + el * cnt
        if size > pos:
            out.append(f'    uint8_t _u{pos:03x}[0x{size - pos:X}];')
        out.append('};')
        out.append(f'_Static_assert(sizeof(struct {name}) == 0x{size:X}, "{name} size");')
        out += asserts
        out.append('')
    out.append('/* typed globals (addresses: structs_main.h; tools/equiv_main_emu.py defines them) */')
    for t, p, n, dims, a in globs:
        if n.startswith('PTR_') or n.startswith('DAT_'):
            continue
        ct, _ = ctype(t, p, esz)
        out.append(f'extern {ct}{"" if ct.endswith("*") else " "}{n}{"".join(f"[{d}]" for d in dims)};'
                   f'   /* @0x{a:08X} */')
    out += ['', '#endif', '']
    return '\n'.join(out)


def globals_map():
    """name -> address of the typed globals (PTR_/DAT_ labels excluded)."""
    return {n: a for _, _, n, _, a in parse()[1] if not (n.startswith('PTR_') or n.startswith('DAT_'))}


def main():
    if sys.argv[1:] == ['--globals']:
        for n, a in globals_map().items():
            print(f'{n}\t{a:08x}')
        return
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    os.makedirs(os.path.dirname(os.path.abspath(sys.argv[1])), exist_ok=True)
    with open(sys.argv[1], 'w', encoding='utf-8') as f:
        f.write(header())
    print(f'main_structs: wrote {sys.argv[1]}')


if __name__ == '__main__':
    main()
