#!/usr/bin/env python3
"""T24 (MAIN): write src/main/out/include/iodefine.h, one access macro per RX651 peripheral register.

The register list is tools/ghidra/sfr_rx651.tsv (T23a: generated from Table 5.1 "List of I/O Registers (Address
Order)" of the RX651 hardware manual r01uh0590ej0240), the same table that gives the decompiled MAIN code its
register names, so the recreated source and decomp/main/ use the same names (SCI0_SCR, ICU_GENBL0, PORT3_PMR...).
Each macro is a volatile lvalue of the register's own width: `SCI0_SCR = 0;` is one byte store to 0x8A002. Registers
wider than 32 bits (the 128-bit rows of the table) are left out. Renesas's iodefine.h (bit-field structs) is not
used: it is part of the Renesas tool packages and not redistributable here. The header is generated at build time
(src/main/Makefile) and not committed: the table is the source.

Usage: python3 -I tools/main_iodefine.py [OUT]
"""
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SFR = os.path.join(ROOT, 'tools/ghidra/sfr_rx651.tsv')
OUT = os.path.join(ROOT, 'src/main/out/include/iodefine.h')


def render():
    rows = [ln.rstrip('\n').split('\t') for ln in open(SFR, encoding='utf-8') if ln.strip() and not ln.startswith('#')]
    out = ['/* RX651 peripheral registers for the recreated MAIN source (T24). Generated by tools/main_iodefine.py from',
           ' * tools/ghidra/sfr_rx651.tsv (RX651 hardware manual r01uh0590ej0240, Table 5.1); do not edit by hand. */',
           '#ifndef IODEFINE_H', '#define IODEFINE_H', '', '#include <stdint.h>', '',
           '#define SFR8(a)  (*(volatile uint8_t *)(a))', '#define SFR16(a) (*(volatile uint16_t *)(a))',
           '#define SFR32(a) (*(volatile uint32_t *)(a))', '']
    for r in rows:
        addr, label, bits, primary = r[0], r[1], r[4], r[6]
        if primary != '1' or bits not in ('8', '16', '32'):
            continue
        out.append(f'#define {label:24s} SFR{bits}(0x{int(addr, 16):05X}u)   /* {r[9]} */')
    out += ['', '#endif', '']
    return '\n'.join(out)


def main():
    text = render()
    out = os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else OUT
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, 'w', encoding='utf-8') as f:
        f.write(text)
    print(f'main_iodefine: wrote {out} ({text.count(chr(10) + "#define ") - 3} registers)')


if __name__ == '__main__':
    main()
