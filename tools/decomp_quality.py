#!/usr/bin/env python3
"""Decompile-quality counts (T21f, issue #97 B11): compare two quality.tsv files, or render them into INDEX.md.

`tools/ghidra/ExportDecomp.java` writes `<outdir>/quality.tsv` (header `metric<TAB>value`, one integer per row) in the same
decompile pass as the `.c` files. Every metric is "lower is better" except the informational ones below.

Usage:
  python3 -I tools/decomp_quality.py compare <committed quality.tsv> <new quality.tsv> [label]
      Prints every metric that changed. Exit 1 if any metric got worse (went up), 0 otherwise. A metric that is
      missing on one side counts as 0 there (a new warning kind is worse, a vanished one is better).
  python3 -I tools/decomp_quality.py index <INDEX.md> <label>=<quality.tsv> [<label>=<quality.tsv> ...]
      Replaces the block between `<!-- quality:begin -->` and `<!-- quality:end -->` in INDEX.md with a Markdown table
      (one column per label). Appends the block at the end if the markers are missing.
"""
import sys

# Not "lower is better": printed when they change, never a failure.
INFO = {'functions'}

BEGIN, END = '<!-- quality:begin -->', '<!-- quality:end -->'

LABELS = {
    'functions': 'Functions exported (non-thunk)',
    'decompile_failures': 'Decompile failures',
    'warnings': 'Decompiler warnings (all kinds)',
    'functions_with_warnings': 'Functions with a warning',
    'spacebase_warnings': '"Unable to track spacebase"',
    'unreachable_block_warnings': '"Removing unreachable block"',
    'halt_baddata': '`halt_baddata()` calls',
    'functions_with_halt_baddata': 'Functions with `halt_baddata()`',
    'functions_with_in_vars': 'Functions with `in_*` variables',
    'functions_with_unaff_vars': 'Functions with `unaff_*` variables',
    'functions_with_extraout_vars': 'Functions with `extraout_*` variables',
    'functions_with_in_unaff_extraout': 'Functions with any of `in_`/`unaff_`/`extraout_`',
    'undefined_nonff_bytes': 'Undefined non-0xFF bytes in executable blocks',
    'bookmarks_error': 'Error bookmarks',
    'bookmarks_bad_instruction': '"Bad Instruction" bookmarks',
}


def load(path):
    rows = {}
    with open(path, encoding='utf-8') as f:
        for n, line in enumerate(f):
            line = line.rstrip('\n')
            if not line or line.startswith('#') or (n == 0 and line.startswith('metric\t')):
                continue
            k, v = line.rsplit('\t', 1)
            rows[k] = int(v)
    return rows


def order(keys):
    """Fixed metrics first (in file order of LABELS), then per-block rows, then warning kinds."""
    fixed = [k for k in LABELS if k in keys]
    rest = sorted(k for k in keys if k not in LABELS)
    return fixed + [k for k in rest if not k.startswith('warning:')] + [k for k in rest if k.startswith('warning:')]


def compare(old_path, new_path, label=''):
    old, new = load(old_path), load(new_path)
    pre = f'{label}: ' if label else ''
    worse = better = 0
    for k in order(set(old) | set(new)):
        a, b = old.get(k, 0), new.get(k, 0)
        if a == b:
            continue
        if k in INFO:
            tag = 'changed'
        elif b > a:
            tag, worse = 'WORSE', worse + 1
        else:
            tag, better = 'better', better + 1
        print(f'{pre}{tag:7} {k}: {a} -> {b}')
    if worse:
        print(f'{pre}{worse} metric(s) got worse, {better} better')
        return 1
    print(f'{pre}no metric got worse ({better} better)')
    return 0


def table(cols):
    data = [(lab, load(p)) for lab, p in cols]
    keys = order(set().union(*(d for _, d in data)))
    out = [BEGIN,
           '<!-- generated by tools/decomp_quality.py index from quality.tsv (ExportDecomp.java); do not edit by hand -->',
           '',
           '| Metric | ' + ' | '.join(lab for lab, _ in data) + ' |',
           '|---|' + '---:|' * len(data)]
    for k in keys:
        if k.startswith('warning:'):
            name = 'warning: ' + k[len('warning:'):].replace('|', '\\|')
        elif k.startswith('undefined_nonff_bytes:'):
            name = '… in block `' + k.split(':', 1)[1] + '`'
        else:
            name = LABELS.get(k, k)
        out.append(f'| {name} | ' + ' | '.join(f'{d.get(k, 0):,}' for _, d in data) + ' |')
    out.append(END)
    return '\n'.join(out) + '\n'


def index(path, specs):
    cols = []
    for s in specs:
        lab, p = s.split('=', 1)
        cols.append((lab, p))
    text = open(path, encoding='utf-8').read()
    block = table(cols)
    if BEGIN in text and END in text:
        a = text.index(BEGIN)
        b = text.index(END) + len(END)
        if text[b:b + 1] == '\n':
            b += 1
        text = text[:a] + block + text[b:]
    else:
        text = text.rstrip('\n') + '\n\n' + block
    open(path, 'w', encoding='utf-8').write(text)
    print(f'{path}: quality table with {len(cols)} column(s)', file=sys.stderr)


def main(argv):
    if len(argv) >= 3 and argv[0] == 'compare':
        return compare(argv[1], argv[2], argv[3] if len(argv) > 3 else '')
    if len(argv) >= 3 and argv[0] == 'index':
        index(argv[1], argv[2:])
        return 0
    sys.exit(__doc__)


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
