#!/bin/bash
# T23d: rebuild tools/ghidra/names_ifdsp.lib.tsv (IFDSP M33 library functions) from scratch.
#
#   FRTOS=/path/to/FreeRTOS-Kernel-V10.3.0/FreeRTOS/Source tools/t23d_lib.sh [workdir]
#
# FRTOS is the kernel source tree of FreeRTOS V10.3.0 (github.com/FreeRTOS/FreeRTOS-Kernel, tag V10.3.0 =
# commit 1049fc776a191006831e9802dd4f9c1246bb67ef; the kernel lives in FreeRTOS/Source there). BUILD (default build/)
# holds the decoded images. Needs arm-none-eabi-gcc / arm-none-eabi-objdump (apt gcc-arm-none-eabi; 13.2.1 in T23d).
# FreeRTOSConfig.h comes from tools/t23d_FreeRTOSConfig.h. The DISPLAY and MAIN lib TSVs are reviewed tables without a
# generator, see docs/tasks/T23-readability.md.
set -euo pipefail
ROOT=$(cd "$(dirname "$0")/.." && pwd)
: "${FRTOS:?set FRTOS to the FreeRTOS V10.3.0 kernel source directory}"
W=${1:-$(mktemp -d)}
mkdir -p "$W/cfg" "$W/obj"
cp "$ROOT/tools/t23d_FreeRTOSConfig.h" "$W/cfg/FreeRTOSConfig.h"
P=$FRTOS/portable/GCC/ARM_CM33_NTZ/non_secure
for f in tasks.c queue.c list.c timers.c event_groups.c stream_buffer.c portable/MemMang/heap_4.c; do
  arm-none-eabi-gcc -mcpu=cortex-m33 -mthumb -mfloat-abi=hard -mfpu=fpv5-sp-d16 -Os -ffunction-sections \
    -fdata-sections -fno-common -std=gnu99 -w -I"$W/cfg" -I"$FRTOS/include" -I"$P" -c "$FRTOS/$f" -o "$W/obj/$(basename "$f" .c).o"
done
for f in port.c portasm.c; do
  arm-none-eabi-gcc -mcpu=cortex-m33 -mthumb -mfloat-abi=hard -mfpu=fpv5-sp-d16 -Os -ffunction-sections \
    -fdata-sections -fno-common -std=gnu99 -w -I"$W/cfg" -I"$FRTOS/include" -I"$P" -c "$P/$f" -o "$W/obj/$(basename "$f" .c).o"
done
B=${BUILD:-$ROOT/build}/FT-710_IFDSP_V0101.bin
F=$ROOT/decomp/ifdsp/m33/functions.tsv
O=$ROOT/tools/ghidra/names_ifdsp.lib.tsv
{
  echo "# FT-710 IFDSP M33 library functions (T23d), generated by tools/t23d_lib.sh; do not edit."
  echo "# Columns: address, name, library, version, method, score, previous, evidence."
  echo "# FreeRTOS-Kernel V10.3.0 (commit 1049fc776a19) built with arm-none-eabi-gcc $(arm-none-eabi-gcc -dumpversion) -mcpu=cortex-m33 -Os,"
  echo "# port GCC/ARM_CM33_NTZ, heap_4, matched by tools/lib_match.py; GNU ld long-branch veneers; the startup default handler."
  python3 -I "$ROOT/tools/lib_match.py" match --bin "$B" --file-off 0x5D428 --vma 0x80000 --end 0x87EBC --funcs "$F" \
    --lib FreeRTOS --version V10.3.0 --method lib_match "$W"/obj/*.o | grep -v '^#'
  python3 -I "$ROOT/tools/lib_match.py" veneers --bin "$B" --file-off 0 --vma 0x08000000 --funcs "$F" | grep -v '^#'
  printf '08001220\tDefaultHandler\tMCUXpresso startup\t-\tidiom\t0.900\t%s\t%s\n' \
    "$(grep -P '^08001220\t' "$F" | cut -f2)" \
    'b . loop right after the per-exception b . handlers 0x0800120C..0x0800121E; the 25 weak IRQ handlers without a driver call it'
} > "$O"
echo "wrote $O ($(grep -vc '^#' "$O") rows)"
