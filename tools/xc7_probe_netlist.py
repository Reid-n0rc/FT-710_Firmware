#!/usr/bin/env python3
"""Add a probe output port to the structural netlist, for watching internal nets in Verilator (T15e).

Written for T15e (FT-710 SDR FPGA). Stdlib only. Input and output are derived files (build/, never commit).

Usage:
    python3 -I tools/xc7_probe_netlist.py NETLIST.json IN.v OUT.v OUT.names CELLPIN [CELLPIN ...]
        CELLPIN is CELL (all output pins of the cell, e.g. SLICE_X2Y101/AFF -> Q) or CELL.PIN, or @FILE with one
        per line. OUT.v is IN.v with `output wire [N-1:0] probe` on module ft710_sdr and
        `assign probe[i] = <net of CELLPIN i>;`. OUT.names lists index, cell.pin, net.
        hdl/sdr/sim/full_main.cpp prints probe changes when built with -DPROBE_W=<words>.
    Options (before the positional arguments):
        --ports HDR   write 32-bit ports probe_w<k> instead of one wide `probe` port (Verilator cannot compile a port of
                      tens of thousands of bits in reasonable time, #172) and HDR, a header for ddc_main.cpp's
                      -DPROBE_PORTS build (build_full.sh PROBE_PORTS=1; put HDR in the object directory as probe_ports.h)
        --declared    drop probes whose net is not declared in IN.v (unloaded outputs such as unused CARRY4 O pins)
"""
import json
import re
import sys


def main():
    args = sys.argv[1:]
    hdr, declared = None, False
    while args and args[0].startswith("--"):
        if args[0] == "--ports":
            hdr = args[1]
            args = args[2:]
        elif args[0] == "--declared":
            declared = True
            args = args[1:]
        else:
            sys.exit(__doc__)
    if len(args) < 5:
        sys.exit(__doc__)
    nlp, inp, outp, namesp = args[0:4]
    refs = []
    for a in args[4:]:
        if a.startswith("@"):
            refs += [x.strip() for x in open(a[1:]) if x.strip() and not x.startswith("#")]
        else:
            refs.append(a)
    nl = json.load(open(nlp))
    cells = {c["name"]: c for c in nl["cells"]}
    probes = []
    for r in refs:
        if r in cells:
            pins = [(p, v[0]) for p, v in sorted(cells[r]["pins"].items()) if v[1] == "O"]
        else:
            c, p = r.rsplit(".", 1)
            pins = [(p, cells[c]["pins"][p][0])]
        for p, n in pins:
            if n.startswith("1'b"):
                continue
            probes.append(("%s.%s" % (r.split(".")[0] if r in cells else c, p), n))
    src = open(inp).read()
    if declared:
        names = set(re.findall(r"^\s*wire (\S+);", src, re.M))
        probes = [pr for pr in probes if pr[1] in names]
    head, sep, rest = src.partition("module ft710_sdr (\n")
    assert sep, "module header not found"
    n = len(probes)
    words = (n + 31) // 32
    if hdr:
        src = head + sep + "".join("  output wire [31:0] probe_w%d,\n" % w for w in range(words)) + rest
        nets = [net for _, net in probes] + ["1'b0"] * (32 * words - n)
        body = "".join("  assign probe_w%d = {%s};\n" % (w, ", ".join(nets[32 * w + b] for b in range(31, -1, -1)))
                       for w in range(words))
        with open(hdr, "w") as f:   # included inside main(), where `top` exists
            f.write("// generated by tools/xc7_probe_netlist.py --ports\n")
            f.write("IData* probe_ptr[%d] = {%s};\n" % (words, ", ".join("&top->probe_w%d" % w for w in range(words))))
            f.write("#define PROBE_WORD(w) (*probe_ptr[w])\n")
    else:
        src = head + sep + "  output wire [%d:0] probe,\n" % (n - 1) + rest
        body = "".join("  assign probe[%d] = %s;\n" % (k, net) for k, (_, net) in enumerate(probes))
    i = src.rindex("endmodule")
    src = src[:i] + body + src[i:]
    open(outp, "w").write(src)
    with open(namesp, "w") as f:
        for k, (cp, net) in enumerate(probes):
            f.write("%d\t%s\t%s\n" % (k, cp, net))
    print("%d probes, %d words" % (n, (n + 31) // 32))


if __name__ == "__main__":
    main()
