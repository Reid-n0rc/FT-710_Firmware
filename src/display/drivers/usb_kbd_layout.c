#define N_OF(a) (sizeof(a) / sizeof((a)[0]))

static void kbd_layout_apply(kbd_key_t *t, const kbd_key_init_t *k, uint32_t n)
{
    for (uint32_t i = 0; i < n; i++)
    {
        kbd_key_t *e = &t[k[i].slot];

        e->usage = k[i].usage;
        e->modifier = k[i].modifier;
        e->ch = k[i].ch;
    }
}

/* 0x20108BC8: (layout): the common entries: Backspace, Enter, CapsLock, Space, the arrows, '1'..'9' (usage
 * 0x1E.. -> slots 9..17), 'A'..'Z' (usage 4.. -> slots 18..43), the keypad, F1..F12 and the modifiers; slots 44, 45
 * and 113..127 stay as they are [fact: 0x20108C90..0x20108CE0 the two loops; the rest from the extraction] */
void kbd_layout_base_fill(int layout)
{
    kbd_key_t *t = kbd_layouts[layout];

    kbd_layout_apply(t, kbd_base_keys, 9);
    for (int i = 1; i <= 9; i++)
    {
        t[8 + i].usage = 0x1D + i;
        t[8 + i].modifier = 0;
        t[8 + i].ch = '0' + i;
    }
    for (int i = 0; i < 26; i++)
    {
        t[18 + i].usage = 4 + i;
        t[18 + i].modifier = 0;
        t[18 + i].ch = 'A' + i;
    }
    kbd_layout_apply(t, kbd_base_keys + 9, N_OF(kbd_base_keys) - 9);
}

/* 0x201090A0: table 0 (JPN) is the base alone [fact: mov r0, #0; b kbd_layout_base_fill] */
void kbd_layout_jpn_init(void)
{
    kbd_layout_base_fill(0);
}

#define KBD_LAYOUT(fn, n, keys)                                 \
    void fn(void)                                               \
    {                                                           \
        kbd_layout_base_fill(n);                                \
        kbd_layout_apply(kbd_layouts[n], keys, N_OF(keys));     \
    }

