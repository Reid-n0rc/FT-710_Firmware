/*
 * FT-710 DISPLAY (T24 USB track): the USB keyboard layout tables, 0x20108BC8..0x2010A757: the eleven KEYBOARD
 * LANGUAGE tables (0 JPN, 1 US, 2 UK, 3 FRA(AZ), 4 FRA(QW), 5 DEU, 6 POR, 7 POR(BR), 8 ESP, 9 ESP(LA), 10 ITA;
 * docs/code/display/input.md "USB keyboard and mouse"), their builders and the character lookup.
 *
 * Each table is 128 entries of {HID usage, modifier, character} words, 0x600 bytes, at 0x20450290 + 0x600 * layout
 * [fact: kbd_layout_base_fill 0x20108BCC..0x20108BF4: layout * 3 << 9]. Modifier 0 = no shift, 1 = shift, 0xFE = any
 * [fact: kbd_char_lookup 0x2010A6F0]. The characters are the GUI's key codes (0x08 Backspace, 0x0D Enter, 0x14
 * CapsLock, 0x25..0x28 the arrows, 0xB1.. shifted digits and punctuation), not ASCII above 0x7F.
 *
 * The builders are straight-line stores in the image (kbd_layout_us_init: 432 bytes of mov/str); here they are
 * tables. The entries are the words each builder writes, found by running it in Unicorn on a table filled with 0x00
 * and with 0xFF (a word that comes out the same both times is written), less the words where it only rewrites the
 * base value. Every builder writes whole entries and only its own table [fact: that extraction; the check compares
 * the whole table after each run].
 */
