/* [fact: 0x84E24] upper case flag -> add 32; no range check, so c must be -128..255 */
int tolower(int c)
{
    return (redlib_ctype_table[c] & _CT_UPPER) ? c + 32 : c;
}

int toupper(int c)
{
    return (redlib_ctype_table[c] & _CT_LOWER) ? c - 32 : c;
}
