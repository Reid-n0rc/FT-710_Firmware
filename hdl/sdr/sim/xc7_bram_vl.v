// Behavioural block-RAM models for the recovered FT-710 SDR netlist (#164): RAMB18E1 and RAMB36E1.
//
// Written for Verilator 5 (hdl/sdr/sim/build_full.sh). Yosys' cells_sim.v declares RAMB18E1/RAMB36E1 without any
// behaviour, so before #164 every block RAM of the whole-design simulation read as 0. Semantics from UG473
// (7 Series FPGAs Memory Resources): port widths 1/2/4/9/18/36 (RAMB36 also SDP 72, RAMB18 SDP 36), INIT_xx/INITP_xx
// layout (entry i of a W-wide port = INIT bits [i*d +: d], parity INITP bits [i*p +: p]), byte write enables,
// WRITE_FIRST / READ_FIRST / NO_CHANGE, optional output register (DOx_REG) with RSTREG_PRIORITY, inverted control
// pins (IS_*_INVERTED; prjxray's ZINV_* features). Not modelled: cascade (RAMB36 address bit 15), ECC, FIFO mode,
// INIT_A/B and SRVAL_A/B other than 0 (all 0 in this bitstream), address collisions between the two ports (each
// port's write is visible to the other port's read on the same edge or the next one, depending on evaluation order).
// Generated by a one-off script (parameter lists); the core is hand-written. Not for synthesis.
/* verilator lint_off UNUSEDSIGNAL */
/* verilator lint_off UNUSEDPARAM */
/* verilator lint_off BLKSEQ */
/* verilator lint_off WIDTH */
`default_nettype none
// d = data bits, p = parity bits, s = address shift of a port width W
`define XB_D(W) ((W) == 72 ? 64 : (W) == 36 ? 32 : (W) == 18 ? 16 : (W) == 9 ? 8 : (W))
`define XB_P(W) ((W) == 72 ? 8 : (W) == 36 ? 4 : (W) == 18 ? 2 : (W) == 9 ? 1 : 0)
`define XB_S(W) ((W) == 72 ? 6 : (W) == 36 ? 5 : (W) == 18 ? 4 : (W) == 9 ? 3 : (W) == 4 ? 2 : (W) == 2 ? 1 : 0)
module xc7_bram_mem #(parameter integer NW = 1024, parameter integer AW = 14,
                      parameter [NW*16-1:0] INITD = 0, parameter [NW*2-1:0] INITPD = 0,
                      parameter SDP = 0,
                      parameter integer RWA = 18, WWA = 18, RWB = 18, WWB = 18,
                      parameter WMODEA = "WRITE_FIRST", WMODEB = "WRITE_FIRST",
                      parameter integer DOAREG = 0, DOBREG = 0,
                      parameter RSTPA = "RSTREG", RSTPB = "RSTREG")
  (input wire clka, ena, rstrama, rstrega, regcea, input wire [15:0] addra,
   input wire [63:0] dia, input wire [7:0] dipa, input wire [7:0] wea,
   input wire clkb, enb, rstramb, rstregb, regceb, input wire [15:0] addrb,
   input wire [63:0] dib, input wire [7:0] dipb, input wire [7:0] web,
   output wire [63:0] doa, output wire [7:0] dopa, output wire [63:0] dob, output wire [7:0] dopb);
  reg [15:0] m [0:NW-1];
  reg [1:0] mp [0:NW-1];
  integer i;
  initial for (i = 0; i < NW; i = i + 1) begin m[i] = INITD[16*i +: 16]; mp[i] = INITPD[2*i +: 2]; end

  // read one entry of width W at address a -> {parity, data}
  function automatic [71:0] rd(input integer W, input [15:0] a);
    integer d, p, s, e, w, o, k;
    reg [63:0] dv; reg [7:0] pv;
    begin
      d = `XB_D(W); p = `XB_P(W); s = `XB_S(W);
      e = (a & ((1 << AW) - 1)) >> s;
      dv = 0; pv = 0;
      if (d <= 16) begin
        w = (e * d) >> 4; o = (e * d) & 15;
        dv = (m[w] >> o) & ((1 << d) - 1);
      end else
        for (k = 0; k < d / 16; k = k + 1) dv[16*k +: 16] = m[e * (d / 16) + k];
      if (p == 1) pv[0] = mp[e >> 1][e & 1];
      else if (p == 2) pv[1:0] = mp[e];
      else if (p > 2) for (k = 0; k < p / 2; k = k + 1) pv[2*k +: 2] = mp[e * (p / 2) + k];
      rd = {pv, dv};
    end
  endfunction

  // write one entry of width W at address a, byte enables be (d >= 16) or be[0] (d <= 8)
  task automatic wr(input integer W, input [15:0] a, input [63:0] dv, input [7:0] pv, input [7:0] be);
    integer d, p, s, e, w, o, k;
    reg [15:0] mask;
    begin
      d = `XB_D(W); p = `XB_P(W); s = `XB_S(W);
      e = (a & ((1 << AW) - 1)) >> s;
      if (d <= 8) begin
        if (be[0]) begin
          w = (e * d) >> 4; o = (e * d) & 15;
          mask = ((1 << d) - 1) << o;
          m[w] = (m[w] & ~mask) | ((dv[15:0] << o) & mask);
          if (p == 1) mp[e >> 1][e & 1] = pv[0];
        end
      end else
        for (k = 0; k < d / 16; k = k + 1) begin
          w = e * (d / 16) + k;
          if (be[2*k]) begin m[w][7:0] = dv[16*k +: 8]; mp[w][0] = pv[2*k]; end
          if (be[2*k+1]) begin m[w][15:8] = dv[16*k+8 +: 8]; mp[w][1] = pv[2*k+1]; end
        end
    end
  endtask

  reg [71:0] lata = 0, latb = 0, rega = 0, regb = 0;
  wire wra = (SDP == 0) && (|wea);
  always @(posedge clka) begin
    if (ena) begin
      if (wra && WMODEA == "WRITE_FIRST") wr(WWA, addra, dia, dipa, wea);
      if (rstrama) lata <= 0;
      else if (!(wra && WMODEA == "NO_CHANGE")) lata <= rd(RWA, addra);
      if (wra && WMODEA != "WRITE_FIRST") wr(WWA, addra, dia, dipa, wea);
    end
    if (RSTPA == "REGCE") begin if (regcea) rega <= rstrega ? 72'b0 : lata; end
    else if (rstrega) rega <= 0; else if (regcea) rega <= lata;
  end
  wire wrb = |web;
  always @(posedge clkb) begin
    if (enb) begin
      if (SDP != 0) begin
        if (wrb) wr(WWB, addrb, dib, dipb, web);
      end else begin
        if (wrb && WMODEB == "WRITE_FIRST") wr(WWB, addrb, dib, dipb, web);
        if (rstramb) latb <= 0;
        else if (!(wrb && WMODEB == "NO_CHANGE")) latb <= rd(RWB, addrb);
        if (wrb && WMODEB != "WRITE_FIRST") wr(WWB, addrb, dib, dipb, web);
      end
    end
    if (RSTPB == "REGCE") begin if (regceb) regb <= rstregb ? 72'b0 : latb; end
    else if (rstregb) regb <= 0; else if (regceb) regb <= latb;
  end
  wire [71:0] qa = DOAREG ? rega : lata;
  wire [71:0] qb = DOBREG ? regb : latb;
  assign doa = qa[63:0]; assign dopa = qa[71:64];
  assign dob = qb[63:0]; assign dopb = qb[71:64];
endmodule

